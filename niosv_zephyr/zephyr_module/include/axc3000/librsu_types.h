/* The Linux fixed-width types libRSU's interface uses (<librsu.h>), on Zephyr */
#ifndef AXC3000_LIBRSU_TYPES_H_
#define AXC3000_LIBRSU_TYPES_H_
#include <stdint.h>
#include <sys/types.h>
typedef uint8_t  __u8;
typedef int8_t   __s8;
typedef uint16_t __u16;
typedef int16_t  __s16;
typedef uint32_t __u32;
typedef int32_t  __s32;
typedef uint64_t __u64;
typedef int64_t  __s64;
#endif
